#!/usr/bin/env python3
# One-time: create the person-detection schema in the Oracle Autonomous DB (23ai) and prove the
# VECTOR round-trip works. Connects in oracledb THIN mode (pure python, no Instant Client) using the
# downloaded wallet. Credentials come from files in the wallet dir (chmod 600), never hard-coded.
#
# This DB is the detection store ONLY — fully separate from the recorder's SQLite (decoupling rule).
import os, sys, array, oracledb

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import adb                                    # shared Oracle connection (creds from wallet files)

conn = adb.connect()
print("connected; server version:", conn.version)
cur = conn.cursor()


def ddl(sql):
    try:
        cur.execute(sql)
        print("  created:", sql.split("(")[0].split()[2])
    except oracledb.DatabaseError as e:
        if "ORA-00955" in str(e):          # name is already used by an existing object
            print("  exists: ", sql.split("(")[0].split()[2])
        else:
            raise


# identity = a person. name NULL until the user tags it; kind flips to 'known' when named.
ddl("""CREATE TABLE identities (
  id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     VARCHAR2(100),
  kind     VARCHAR2(10) DEFAULT 'unknown',
  created  TIMESTAMP DEFAULT SYSTIMESTAMP
)""")

# one row per detected person-crop, with its 512-d re-ID embedding.
ddl("""CREATE TABLE detections (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts          NUMBER NOT NULL,
  seg_id      NUMBER,
  box         VARCHAR2(100),
  score       BINARY_FLOAT,
  embedding   VECTOR(512, FLOAT32),
  identity_id NUMBER,
  confirmed   NUMBER(1) DEFAULT 0,
  created     TIMESTAMP DEFAULT SYSTIMESTAMP
)""")

# user feedback events — the signal the recognition improves from.
ddl("""CREATE TABLE labels (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  detection_id NUMBER,
  identity_id  NUMBER,
  action       VARCHAR2(20),
  created      TIMESTAMP DEFAULT SYSTIMESTAMP
)""")

# progress marker so the poller knows the last segment it processed (decoupled from nvr.db)
ddl("""CREATE TABLE detect_state (
  k  VARCHAR2(40) PRIMARY KEY,
  v  NUMBER
)""")

try:
    cur.execute("CREATE INDEX det_ts ON detections(ts)"); print("  created: det_ts")
except oracledb.DatabaseError as e:
    print("  exists:  det_ts" if "ORA-00955" in str(e) else e)

# --- VECTOR round-trip proof ---
v = array.array("f", [0.1] * 512)
cur.execute("INSERT INTO detections (ts, box, score, embedding) VALUES (:1,:2,:3,:4)",
            (1, "0,0,1,1", 0.99, v))
conn.commit()
cur.execute("""SELECT id, VECTOR_DISTANCE(embedding, :1, COSINE) d
               FROM detections ORDER BY d FETCH FIRST 1 ROWS ONLY""", [v])
row = cur.fetchone()
print("VECTOR round-trip OK:", row, "(distance ~0 means identical vector matched)")
cur.execute("DELETE FROM detections WHERE ts=1"); conn.commit()

print("tables:", [r[0] for r in cur.execute(
    "SELECT table_name FROM user_tables ORDER BY table_name")])
conn.close()
print("done.")
